        private static async Task<JsonElement> StatusScreenAsync(NpgsqlConnection c, string role = null, bool readOnly = true)
        {
            await using var tx = await c.BeginTransactionAsync(System.Data.IsolationLevel.RepeatableRead);
            await using (var setup = new NpgsqlCommand((readOnly ? "SET TRANSACTION READ ONLY; " : "") +
                "SELECT set_config('aqua.clean_start.tenant','1',true),set_config('aqua.clean_start.boundary',@boundary,true)," +
                "set_config('aqua.clean_start.reset_id',@reset,true)", c, tx))
            { setup.Parameters.AddWithValue("boundary", Boundary.ToString("O")); setup.Parameters.AddWithValue("reset", ResetId); await setup.ExecuteNonQueryAsync(); }
            if (role != null)
            {
                // The role is generated by this fixture, never supplied by a caller.
                await using var selectRole = new NpgsqlCommand("SET LOCAL ROLE " + role, c, tx);
                await selectRole.ExecuteNonQueryAsync();
            }
            await using var query = new NpgsqlCommand(await File.ReadAllTextAsync(Path.Combine(Operations, "preflight-checks.sql")), c, tx);
            using var receipt = JsonDocument.Parse((string)await query.ExecuteScalarAsync());
            await tx.RollbackAsync();
            return receipt.RootElement.Clone();
        }

