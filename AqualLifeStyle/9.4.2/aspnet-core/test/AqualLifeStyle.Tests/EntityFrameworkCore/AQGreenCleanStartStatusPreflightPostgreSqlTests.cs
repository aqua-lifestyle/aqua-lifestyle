        [Fact]
        public async Task StatusOnlyReadOnlyAndCompleteVisibilityCannotBeInferredFromFilteredZeros()
        {
            await using var lease = await _fixture.CreateDatabaseAsync();
            await using var c = new NpgsqlConnection(lease.ConnectionString()); await c.OpenAsync(); await PrepareAsync(c);
            var role = "synthetic_screen_" + Guid.NewGuid().ToString("N");
            await SqlAsync(c,"CREATE ROLE " + role + " NOLOGIN; GRANT USAGE ON SCHEMA public TO " + role +
                "; GRANT SELECT ON ALL TABLES IN SCHEMA public TO " + role);
            await SqlAsync(c,"REVOKE EXECUTE ON FUNCTION pg_catalog.pg_control_system() FROM PUBLIC");
            ((bool)await SqlAsync(c,"SELECT has_function_privilege('" + role + "','pg_catalog.pg_control_system()','EXECUTE')")).ShouldBeFalse();
            // The unchanged data checks need SELECT, not the native control-file function.
            var clear = await StatusScreenAsync(c,role);
